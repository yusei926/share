MANIFEST_NAME = "meta/curation/manifest.json"
MANIFEST_SCHEMA = "team_ramen_flip_table_curated_dataset/v1"
OWNED_MARKER = ".flip_table_curation_owned"
VIDEO_PIPELINE_VERSION = "ffmpeg_select_setpts_cfr_v2"


class Stats:
    def __init__(self, width: int) -> None:
        self.width = width
        self.count = 0
        self.minimum = np.full(width, np.inf)
        self.maximum = np.full(width, -np.inf)
        self.total = np.zeros(width)
        self.total_sq = np.zeros(width)

    def update(self, values: np.ndarray) -> None:
        matrix = np.asarray(values, dtype=np.float64).reshape(-1, self.width)
        self.count += len(matrix)
        self.minimum = np.minimum(self.minimum, np.min(matrix, axis=0))
        self.maximum = np.maximum(self.maximum, np.max(matrix, axis=0))
        self.total += np.sum(matrix, axis=0)
        self.total_sq += np.sum(matrix * matrix, axis=0)

    def json(self) -> dict[str, Any]:
        mean = self.total / self.count
        variance = np.maximum(self.total_sq / self.count - mean * mean, 0.0)
        return {
            "min": self.minimum.tolist(),
            "max": self.maximum.tolist(),
            "mean": mean.tolist(),
            "std": np.sqrt(variance).tolist(),
            "count": [self.count],
        }


def dataset_root(config: CurationConfig) -> Path:
    return (
        config.workspace
        / "dataset"
        / config.target_repo_id.replace("/", "__")
    )


def _prepare_root(root: Path) -> None:
    if root.exists():
        marker = root / OWNED_MARKER
        if not marker.is_file():
            raise RuntimeError(f"refusing to replace unowned directory {root}")
        shutil.rmtree(root)
    root.mkdir(parents=True)
    (root / OWNED_MARKER).write_text("generated by flip_table_dataset_curation\n")


def _selection_digest(
    config: CurationConfig, selected: list[dict[str, Any]]
) -> str:
    return sha256_json(
        {
            "source_revision": config.source_revision,
            "video_pipeline_version": VIDEO_PIPELINE_VERSION,
            "video": config.section("video"),
            "episodes": [
                {
                    "source_episode_index": int(record["source_episode_index"]),
                    "trim_start": int(record["trim_start"]),
                    "trim_length": int(record["trim_length"]),
                }
                for record in selected
            ],
        }
    )


def _cache_existing_videos(
    root: Path,
    config: CurationConfig,
    selected: list[dict[str, Any]],
) -> Path:
    digest = _selection_digest(config, selected)
    cache = config.workspace / "video_cache" / digest
    manifest_path = root / MANIFEST_NAME
    if cache.exists() or not manifest_path.is_file():
        return cache
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    if manifest.get("video_pipeline_version") != VIDEO_PIPELINE_VERSION:
        return cache
    previous = [
        (
            int(row["source_episode_index"]),
            int(row["source_frame_start"]),
            int(row["length"]),
        )
        for row in manifest.get("episodes", [])
    ]
    current = [
        (
            int(record["source_episode_index"]),
            int(record["trim_start"]),
            int(record["trim_length"]),
        )
        for record in selected
    ]
    if previous != current:
        return cache
    expected_hashes = manifest.get("file_sha256", {})
    for path in sorted((root / "videos").glob("**/*.mp4")):
        relative = path.relative_to(root).as_posix()
        if expected_hashes.get(relative) != sha256_file(path):
            raise RuntimeError(f"existing video cache candidate failed hash: {path}")
        target = cache / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        os.link(path, target)
    return cache


def _replace_columns(
    table: pa.Table,
    *,
    episode_index: int,
    global_start: int,
    fps: int,
) -> pa.Table:
    length = len(table)
    replacements = {
        "timestamp": pa.array(
            np.arange(length, dtype=np.float32) / np.float32(fps), type=pa.float32()
        ),
        "frame_index": pa.array(np.arange(length, dtype=np.int64)),
        "episode_index": pa.array(
            np.full(length, episode_index, dtype=np.int64)
        ),
        "index": pa.array(
            np.arange(global_start, global_start + length, dtype=np.int64)
        ),
        "task_index": pa.array(np.zeros(length, dtype=np.int64)),
    }
    result = table
    for key, value in replacements.items():
        column = result.schema.get_field_index(key)
        result = result.set_column(column, key, value)
    return result


def _ffmpeg_select_expression(intervals: list[tuple[int, int]]) -> str:
    terms = [f"between(n\\,{start}\\,{end - 1})" for start, end in intervals]
    return "+".join(terms)


def _repack_videos(
    *,
    snapshot,
    selected: list[dict[str, Any]],
    source_rows: dict[int, dict[str, Any]],
    root: Path,
    config: CurationConfig,
    cache_root: Path,
) -> dict[tuple[str, int], dict[str, float | int]]:
    settings = config.section("video")
    mapping: dict[tuple[str, int], dict[str, float | int]] = {}
    for key in VIDEO_KEYS:
        groups: dict[Path, list[tuple[int, int, int]]] = defaultdict(list)
        for record in selected:
            source_episode = int(record["source_episode_index"])
            row = source_rows[source_episode]
            source_path = snapshot.video_path(row, key)
            absolute_start = int(
                round(snapshot.video_offset(row, key) * snapshot.fps)
            ) + int(record["trim_start"])
            absolute_end = absolute_start + int(record["trim_length"])
            groups[source_path].append(
                (absolute_start, absolute_end, source_episode)
            )
        for output_file_index, (source_path, entries) in enumerate(
            sorted(groups.items(), key=lambda item: str(item[0]))
        ):
            entries.sort()
            for previous, current in zip(entries, entries[1:], strict=False):
                if current[0] < previous[1]:
                    raise RuntimeError(
                        f"overlapping selected intervals in {source_path}: {previous}, {current}"
                    )
            output = (
                root
                / "videos"
                / key
                / "chunk-000"
                / f"file-{output_file_index:03d}.mp4"
            )
            output.parent.mkdir(parents=True, exist_ok=True)
            expression = _ffmpeg_select_expression(
                [(start, end) for start, end, _ in entries]
            )
            command = [
                "ffmpeg",
                "-y",
                "-loglevel",
                "error",
                "-i",
                str(source_path),
                "-vf",
                f"select='{expression}',setpts=N/({snapshot.fps}*TB)",
                "-an",
                "-fps_mode",
                "cfr",
                "-r",
                str(snapshot.fps),
                "-c:v",
                str(settings["codec"]),
                "-preset",
                str(settings["preset"]),
                "-crf",
                str(settings["crf"]),
                "-pix_fmt",
                str(settings["pixel_format"]),
                "-g",
                str(settings["gop"]),
                "-movflags",
                "+faststart",
                str(output),
            ]
            cached = cache_root / output.relative_to(root)
            reused = cached.is_file()
            if reused:
                os.link(cached, output)
            else:
                subprocess.run(command, check=True)
                cached.parent.mkdir(parents=True, exist_ok=True)
                os.link(output, cached)
            cumulative = 0
            for start, end, source_episode in entries:
                length = end - start
                mapping[(key, source_episode)] = {
                    "chunk_index": 0,
                    "file_index": output_file_index,
                    "from_timestamp": cumulative / snapshot.fps,
                    "to_timestamp": (cumulative + length) / snapshot.fps,
                }
                cumulative += length
            source = "cache" if reused else "encoded"
            print(
                f"[video] {key} file={output_file_index} "
                f"frames={cumulative} source={source}"
            )
    return mapping


def _video_stats(
    root: Path, info: dict[str, Any], *, samples_per_file: int = 32
) -> dict[str, dict[str, Any]]:
    result: dict[str, dict[str, Any]] = {}
    for key in VIDEO_KEYS:
        pixels: list[np.ndarray] = []
        files = sorted((root / "videos" / key).glob("chunk-*/*.mp4"))
        for path in files:
            capture = cv2.VideoCapture(str(path))
            frames = int(capture.get(cv2.CAP_PROP_FRAME_COUNT))
            for frame_index in np.linspace(
                0, max(0, frames - 1), min(samples_per_file, frames), dtype=int
            ):
                capture.set(cv2.CAP_PROP_POS_FRAMES, int(frame_index))
                ok, frame = capture.read()
                if not ok:
                    continue
                rgb = cv2.cvtColor(
                    cv2.resize(frame, (160, 120)), cv2.COLOR_BGR2RGB
                )
                pixels.append(rgb.reshape(-1, 3).astype(np.float32) / 255.0)
            capture.release()
        if not pixels:
            raise RuntimeError(f"failed to sample video statistics for {key}")
        matrix = np.concatenate(pixels, axis=0)
        channel = matrix.T
        result[key] = {
            "min": [[[float(value)]] for value in np.min(channel, axis=1)],
            "max": [[[float(value)]] for value in np.max(channel, axis=1)],
            "mean": [[[float(value)]] for value in np.mean(channel, axis=1)],
            "std": [[[float(value)]] for value in np.std(channel, axis=1)],
            "count": [int(matrix.shape[0])],
            "q01": [[[float(value)]] for value in np.quantile(channel, 0.01, axis=1)],
            "q10": [[[float(value)]] for value in np.quantile(channel, 0.10, axis=1)],
            "q50": [[[float(value)]] for value in np.quantile(channel, 0.50, axis=1)],
            "q90": [[[float(value)]] for value in np.quantile(channel, 0.90, axis=1)],
            "q99": [[[float(value)]] for value in np.quantile(channel, 0.99, axis=1)],
            "sampling": {
                "method": "deterministic_uniform_frames_downsampled_160x120",
                "samples_per_file": samples_per_file,
            },
        }
    return result


def _dataset_card(
    config: CurationConfig, *, selected: list[dict[str, Any]], report: dict[str, Any]
) -> str:
    summary = report["summary"]
    split_counts = {
        name: sum(record["split"] == name for record in selected)
        for name in ("train", "validation", "test")
    }
    return f"""---
license: other
task_categories:
- robotics
tags:
- lerobot
- unitree-g1
- imitation-learning
---

# IROS2026 RAMEN Suzuki Flip Table 2

`{config.source_repo_id}` の immutable revision
`{config.source_revision}` を自動キュレーションした private LeRobot v3 datasetです。

## 収録内容

- 採用 episode: {len(selected)}
- split: {json.dumps(split_counts, ensure_ascii=False)}
- FPS: 30
- RGB 4系統、IR 4系統
- 元の数値state/actionは変更せず、前1秒・後2秒を残すtrimのみ実施

## 採用条件

- 足先world FKで一歩も検出されない
- 初期状態でテーブル短辺がロボット正面にあると確認した向きクラスタ
- 代表動画で確認した最多の安定flip軌道クラスタ

元531 episodeのうち歩行検出は{summary['walking_detected']}件、
trim不成立は{summary['trim_invalid']}件です。episodeごとの根拠と除外理由は
`meta/curation/manifest.json` にあります。

個々の成功を全件人手確認したdatasetではないため、虚偽の`success=true`は
付与していません。採用行はepisode metadataの
`curation_status=accepted_auto`で識別します。
"""


def build_dataset(config: CurationConfig, *, maximum_episodes: int | None = None) -> Path:
    analysis_path = config.workspace / "analysis" / "analysis.json"
    decision_path = config.workspace / "decision.json"
    if not analysis_path.is_file() or not decision_path.is_file():
        raise RuntimeError("analyze and representative review decision are required")
    analysis = json.loads(analysis_path.read_text(encoding="utf-8"))
    decision = json.loads(decision_path.read_text(encoding="utf-8"))
    if analysis.get("schema_version") != ANALYSIS_SCHEMA:
        raise ValueError("unsupported analysis schema")
    if decision.get("schema_version") != DECISION_SCHEMA:
        raise ValueError("unsupported decision schema")
    if analysis.get("decision") != decision:
        raise RuntimeError("run analyze again after recording the decision")
    selected = [
        record
        for record in analysis["records"]
        if record["curation_status"] == "accepted_auto"
    ]
    # LeRobot split ranges are contiguous episode-index intervals. Keep source
    # order within each split, but group splits before assigning new indices.
    split_order = {"train": 0, "validation": 1, "test": 2}
    selected.sort(
        key=lambda record: (
            split_order[record["split"]],
            int(record["source_episode_index"]),
        )
    )
    if maximum_episodes is not None:
        selected = selected[:maximum_episodes]
    minimum = (
        1 if maximum_episodes is not None else int(config.section("target")["minimum_episodes"])
    )
    if len(selected) < minimum:
        raise RuntimeError(f"only {len(selected)} accepted episodes; minimum={minimum}")

    snapshot = download_source(config, include_videos=True, rgb_only=False)
    source_table = read_numeric_table(snapshot)
    source_rows = {int(row["episode_index"]): row for row in snapshot.episodes}
    root = dataset_root(config)
    cache_root = _cache_existing_videos(root, config, selected)
    _prepare_root(root)
    (root / ".gitattributes").write_text(
        "*.parquet filter=lfs diff=lfs merge=lfs -text\n"
        "*.mp4 filter=lfs diff=lfs merge=lfs -text\n",
        encoding="utf-8",
    )
    numeric_stats = {key: Stats(width) for key, width in NUMERIC_WIDTHS.items()}
    scalar_stats = {key: Stats(1) for key in INDEX_KEYS}
    episode_tables: list[pa.Table] = []
    metadata_rows: list[dict[str, Any]] = []
    global_index = 0
    for new_episode, record in enumerate(selected):
        source_episode = int(record["source_episode_index"])
        source_row = source_rows[source_episode]
        source_episode_table = episode_slice(source_table, source_row)
        start = int(record["trim_start"])
        length = int(record["trim_length"])
        raw_slice = source_episode_table.slice(start, length)
        output_table = _replace_columns(
            raw_slice,
            episode_index=new_episode,
            global_start=global_index,
            fps=snapshot.fps,
        )
        output_path = root / "data" / "chunk-000" / f"file-{new_episode:03d}.parquet"
        output_path.parent.mkdir(parents=True, exist_ok=True)
        pq.write_table(output_table, output_path, compression="snappy")
        episode_tables.append(output_table)
        for key, width in NUMERIC_WIDTHS.items():
            numeric_stats[key].update(np.asarray(output_table[key].to_pylist()))
        for key in INDEX_KEYS:
            scalar_stats[key].update(
                np.asarray(output_table[key].to_pylist(), dtype=np.float64).reshape(-1, 1)
            )
        metadata_rows.append(
            {
                "episode_index": new_episode,
                "tasks": ["flip table"],
                "length": length,
                "dataset_from_index": global_index,
                "dataset_to_index": global_index + length,
                "data/chunk_index": 0,
                "data/file_index": new_episode,
                "source_repo_id": config.source_repo_id,
                "source_revision": config.source_revision,
                "source_episode_index": source_episode,
                "source_episode_name": record["source_episode_name"],
                "source_episode_length": int(record["source_length"]),
                "source_frame_start": start,
                "source_frame_end": start + length,
                "trim_first_active_frame": int(record["first_active"]),
                "trim_last_active_frame": int(record["last_active"]),
                "trim_post_roll_complete": bool(record["post_roll_complete"]),
                "curation_status": "accepted_auto",
                "curation_split": record["split"],
                "curation_orientation_cluster": int(record["orientation_cluster"]),
                "curation_orientation_detection_fraction": float(
                    record["orientation_detection_fraction"]
                ),
                "curation_trajectory_cluster": int(record["trajectory_cluster"]),
                "curation_trajectory_stability": float(
                    record["trajectory_stability"]
                ),
                "curation_step_count": int(record["step_count"]),
                "curation_max_contact_displacement_m": float(
                    record["maximum_contact_displacement_m"]
                ),
                "curation_config_sha256": config.digest,
                "curation_code_sha256": config.code_digest,
                "curation_model_sha256": str(
                    config.section("assets")["yolo_weight_sha256"]
                ),
                "curation_urdf_sha256": str(
                    config.section("assets")["urdf_sha256"]
                ),
            }
        )
        global_index += length

    video_mapping = _repack_videos(
        snapshot=snapshot,
        selected=selected,
        source_rows=source_rows,
        root=root,
        config=config,
        cache_root=cache_root,
    )
    for metadata, record in zip(metadata_rows, selected, strict=True):
        source_episode = int(record["source_episode_index"])
        for key in VIDEO_KEYS:
            mapping = video_mapping[(key, source_episode)]
            for field, value in mapping.items():
                metadata[f"videos/{key}/{field}"] = value

    meta_episodes = root / "meta" / "episodes" / "chunk-000" / "file-000.parquet"
    meta_episodes.parent.mkdir(parents=True, exist_ok=True)
    pq.write_table(pa.Table.from_pylist(metadata_rows), meta_episodes)
    tasks = pa.Table.from_pylist(
        [{"task_index": 0, "__index_level_0__": "flip table"}]
    )
    pq.write_table(tasks, root / "meta" / "tasks.parquet")

    info = json.loads(json.dumps(snapshot.info))
    split_counts = {
        name: sum(record["split"] == name for record in selected)
        for name in ("train", "validation", "test")
    }
    split_ranges: dict[str, str] = {}
    split_start = 0
    for name in ("train", "validation", "test"):
        split_end = split_start + split_counts[name]
        split_ranges[name] = f"{split_start}:{split_end}"
        split_start = split_end
    info.update(
        {
            "total_episodes": len(selected),
            "total_frames": global_index,
            "total_tasks": 1,
            "chunks_size": 1000,
            "data_files_size_in_mb": 100,
            "video_files_size_in_mb": 500,
            "splits": split_ranges,
        }
    )
    atomic_write_json(root / "meta" / "info.json", info)
    stats = {key: value.json() for key, value in numeric_stats.items()}
    stats.update({key: value.json() for key, value in scalar_stats.items()})
    stats.update(_video_stats(root, info))
    atomic_write_json(root / "meta" / "stats.json", stats)

    manifest = {
        "schema_version": MANIFEST_SCHEMA,
        "config_sha256": config.digest,
        "code_sha256": config.code_digest,
        "source_repo_id": config.source_repo_id,
        "source_revision": config.source_revision,
        "target_repo_id": config.target_repo_id,
        "video_pipeline_version": VIDEO_PIPELINE_VERSION,
        "decision": decision,
        "analysis_summary": analysis["summary"],
        "episodes": metadata_rows,
        "split_counts": split_counts,
        "file_sha256": {},
    }
    manifest_path = root / MANIFEST_NAME
    atomic_write_json(manifest_path, manifest)
    manifest["file_sha256"] = file_manifest(
        root, exclude={MANIFEST_NAME, OWNED_MARKER}
    )
    atomic_write_json(manifest_path, manifest)
    (root / "README.md").write_text(
        _dataset_card(config, selected=selected, report=analysis),
        encoding="utf-8",
    )
    # README is written after the first manifest pass; refresh the immutable inventory.
    manifest["file_sha256"] = file_manifest(
        root, exclude={MANIFEST_NAME, OWNED_MARKER}
    )
    atomic_write_json(manifest_path, manifest)
    compare = {
        "source_episodes": len(snapshot.episodes),
        "curated_episodes": len(selected),
        "source_frames": int(snapshot.info["total_frames"]),
        "curated_frames": global_index,
        "walking_rejected": analysis["summary"]["walking_detected"],
        "trim_rejected": analysis["summary"]["trim_invalid"],
        "orientation_clusters": analysis["orientation"]["cluster_sizes"],
        "trajectory_clusters": analysis["trajectory"]["cluster_sizes"],
    }
    atomic_write_json(root / "meta" / "curation" / "comparison.json", compare)
    # comparison is part of the immutable inventory too.
    manifest["file_sha256"] = file_manifest(
        root, exclude={MANIFEST_NAME, OWNED_MARKER}
    )
    atomic_write_json(manifest_path, manifest)
    print(f"[build] root={root} episodes={len(selected)} frames={global_index}")
    return root
