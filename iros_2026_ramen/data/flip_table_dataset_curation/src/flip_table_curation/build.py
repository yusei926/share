class Stats:
    def __init__(self, width: int) -> None:
        self.width = width
        self.count = 0
        self.minimum = np.full(width, np.inf)
        self.maximum = np.full(width, -np.inf)
        self.total = np.zeros(width)
        self.total_sq = np.zeros(width)

    def update(self, values: np.ndarray) -> None:
        matrix = np.asarray(values, dtype=np.float64).reshape(-1, self.width)
        self.count += len(matrix)
        self.minimum = np.minimum(self.minimum, np.min(matrix, axis=0))
        self.maximum = np.maximum(self.maximum, np.max(matrix, axis=0))
        self.total += np.sum(matrix, axis=0)
        self.total_sq += np.sum(matrix * matrix, axis=0)

    def json(self) -> dict[str, Any]:
        mean = self.total / self.count
        variance = np.maximum(self.total_sq / self.count - mean * mean, 0.0)
        return {
            "min": self.minimum.tolist(),
            "max": self.maximum.tolist(),
            "mean": mean.tolist(),
            "std": np.sqrt(variance).tolist(),
            "count": [self.count],
        }


def dataset_root(config: CurationConfig) -> Path:
    return config.workspace / "dataset" / config.target_repo_id.replace("/", "__")


def _prepare_root(root: Path) -> None:
    if root.exists():
        marker = root / OWNED_MARKER
        if not marker.is_file():
            raise RuntimeError(f"refusing to replace unowned directory {root}")
        shutil.rmtree(root)
    root.mkdir(parents=True)
    (root / OWNED_MARKER).write_text("generated by flip_table_dataset_curation\n", encoding="utf-8")


def _replace_columns(table: pa.Table, *, episode_index: int, global_start: int, fps: int) -> pa.Table:
    length = len(table)
    replacements = {
        "timestamp": pa.array(np.arange(length, dtype=np.float32) / np.float32(fps), type=pa.float32()),
        "frame_index": pa.array(np.arange(length, dtype=np.int64)),
        "episode_index": pa.array(np.full(length, episode_index, dtype=np.int64)),
        "index": pa.array(np.arange(global_start, global_start + length, dtype=np.int64)),
        "task_index": pa.array(np.zeros(length, dtype=np.int64)),
    }
    result = table
    for key, value in replacements.items():
        result = result.set_column(result.schema.get_field_index(key), key, value)
    return result


def _ffmpeg_filter(entries: list[tuple[int, int, int]], *, fps: int) -> str:
    """Extract each requested range with an exact output frame count.

    A small number of source wrist-video shards end one frame before their
    metadata range. ``tpad`` deterministically repeats only that final usable
    frame, keeping every output episode aligned to its numeric 30 Hz sample.
    """
    ticks_per_frame = 90000 // fps
    parts: list[str] = []
    labels: list[str] = []
    for index, (start, end, _) in enumerate(entries):
        length = end - start
        label = f"segment{index}"
        parts.append(
            f"[0:v]trim=start_frame={start}:end_frame={end},setpts=PTS-STARTPTS,"
            f"tpad=stop_mode=clone:stop={length},trim=end_frame={length},"
            f"settb=1/90000,setpts=N*{ticks_per_frame}[{label}]"
        )
        labels.append(f"[{label}]")
    total_frames = sum(end - start for start, end, _ in entries)
    if len(labels) == 1:
        output_prefix = labels[0]
    else:
        output_prefix = f"{''.join(labels)}concat=n={len(labels)}:v=1:a=0,"
    parts.append(
        f"{output_prefix}trim=end_frame={total_frames},settb=1/90000,"
        f"setpts=N*{ticks_per_frame}[out]"
    )
    return ";".join(parts)


def _encode_video(source: Path, entries: list[tuple[int, int, int]], output: Path, *, fps: int, settings: dict[str, Any]) -> None:
    output.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(
        [
            "ffmpeg", "-y", "-loglevel", "error", "-i", str(source),
            "-filter_complex", _ffmpeg_filter(entries, fps=fps), "-map", "[out]",
            "-an", "-fps_mode", "cfr", "-r", str(fps), "-video_track_timescale", "90000",
            "-c:v", str(settings["codec"]), "-preset", str(settings["preset"]),
            "-crf", str(settings["crf"]), "-pix_fmt", str(settings["pixel_format"]),
            "-threads", str(settings["ffmpeg_threads"]),
            "-g", str(settings["gop"]), "-movflags", "+faststart", str(output),
        ],
        check=True,
    )


def _plan_entry_groups(entries: list[tuple[int, int, int]], frame_budget: int) -> list[list[tuple[int, int, int]]]:
    groups: list[list[tuple[int, int, int]]] = []
    current: list[tuple[int, int, int]] = []
    current_frames = 0
    for entry in entries:
        length = entry[1] - entry[0]
        if current and current_frames + length > frame_budget:
            groups.append(current)
            current, current_frames = [], 0
        current.append(entry)
        current_frames += length
    if current:
        groups.append(current)
    return groups


def _repack_video_key(*, key: str, snapshot, selected: list[SelectedSegment], root: Path, config: CurationConfig) -> dict[tuple[str, int], dict[str, float | int]]:
    settings = config.section("video")
    max_bytes = int(settings["max_file_size_mb"]) * 1024 * 1024
    frame_budget = int(settings["planning_frames_per_file"])
    source_rows = {int(row["episode_index"]): row for row in snapshot.episodes}
    mapping: dict[tuple[str, int], dict[str, float | int]] = {}
    by_source: dict[Path, list[tuple[int, int, int]]] = defaultdict(list)
    for segment in selected:
        row = source_rows[segment.source_episode_index]
        start = int(round(snapshot.video_offset(row, key) * snapshot.fps)) + segment.source_frame_start
        by_source[snapshot.video_path(row, key)].append((start, start + segment.length, segment.source_episode_index))
    file_index = 0
    for source, entries in sorted(by_source.items(), key=lambda item: str(item[0])):
        entries.sort()
        for previous, current in zip(entries, entries[1:], strict=False):
            if current[0] < previous[1]:
                raise RuntimeError(f"selected source frames overlap in {source}")
        pending = _plan_entry_groups(entries, frame_budget)
        while pending:
            group = pending.pop(0)
            output = root / "videos" / key / "chunk-000" / f"file-{file_index:03d}.mp4"
            _encode_video(source, group, output, fps=snapshot.fps, settings=settings)
            if output.stat().st_size > max_bytes:
                output.unlink()
                if len(group) == 1:
                    raise RuntimeError(f"single selected segment exceeds {settings['max_file_size_mb']} MB: {key}")
                midpoint = len(group) // 2
                pending[0:0] = [group[:midpoint], group[midpoint:]]
                continue
            cumulative = 0
            for start, end, source_episode in group:
                length = end - start
                mapping[(key, source_episode)] = {
                    "chunk_index": 0,
                    "file_index": file_index,
                    "from_timestamp": cumulative / snapshot.fps,
                    "to_timestamp": (cumulative + length) / snapshot.fps,
                }
                cumulative += length
            print(f"[video] {key} file={file_index} frames={cumulative} bytes={output.stat().st_size}")
            file_index += 1
    return mapping


def _repack_videos(*, snapshot, selected: list[SelectedSegment], root: Path, config: CurationConfig) -> dict[tuple[str, int], dict[str, float | int]]:
    settings = config.section("video")
    workers = min(int(settings["encode_workers"]), len(VIDEO_KEYS))
    with ThreadPoolExecutor(max_workers=workers) as executor:
        mappings = executor.map(
            lambda key: _repack_video_key(
                key=key, snapshot=snapshot, selected=selected, root=root, config=config
            ),
            VIDEO_KEYS,
        )
        result: dict[tuple[str, int], dict[str, float | int]] = {}
        for mapping in mappings:
            result.update(mapping)
    return result


def _write_dataset_card(config: CurationConfig, *, selection: dict[str, Any], episodes: int, frames: int) -> str:
    return f"""---
license: other
task_categories:
- robotics
private: true
---

# Curated Flip-Table Demonstrations

This private LeRobot v3 dataset contains {episodes} manually curated flip-table demonstrations ({frames} frames at 30 Hz).

Selection is fixed to `{config.labels_repo_id}@{config.labels_revision}`: the final `flip_table` label in each source recording must be `success` or `optimal`. Source frames, numeric values, RGB cameras, and IR cameras are preserved; only derived episode/index/timestamp columns are regenerated for the sliced dataset.

See `meta/curation/manifest.json` and `meta/curation/selection.json` for exact provenance and exclusions.
"""


def build_dataset(config: CurationConfig, *, maximum_episodes: int | None = None) -> Path:
    selected, selection_report = load_selection(config)
    if maximum_episodes is not None:
        selected = selected[:maximum_episodes]
    minimum = 1 if maximum_episodes is not None else int(config.section("target")["minimum_episodes"])
    if len(selected) < minimum:
        raise RuntimeError(f"only {len(selected)} selected episodes; minimum={minimum}")
    if maximum_episodes is None and len(selected) != int(config.section("target")["expected_episodes"]):
        raise RuntimeError("selection count differs from the pinned manual-curation contract")
    expected_frames = config.section("target").get("expected_frames")
    actual_frames = sum(segment.length for segment in selected)
    if maximum_episodes is None and expected_frames is not None and actual_frames != int(expected_frames):
        raise RuntimeError("selection frame count differs from the pinned manual-curation contract")
    snapshot = download_source(
        config,
        include_data=True,
        include_videos=True,
        video_episode_indices=(segment.source_episode_index for segment in selected),
    )
    source_table = read_numeric_table(snapshot)
    source_rows = {int(row["episode_index"]): row for row in snapshot.episodes}
    if any(segment.source_episode_index not in source_rows for segment in selected):
        raise RuntimeError("selection refers to a source episode absent from pinned source snapshot")
    root = dataset_root(config)
    _prepare_root(root)
    (root / ".gitattributes").write_text("*.parquet filter=lfs diff=lfs merge=lfs -text\n*.mp4 filter=lfs diff=lfs merge=lfs -text\n", encoding="utf-8")
    numeric_stats = {key: Stats(width) for key, width in NUMERIC_WIDTHS.items()}
    scalar_stats = {key: Stats(1) for key in INDEX_KEYS}
    metadata_rows: list[dict[str, Any]] = []
    global_index = 0
    for episode_index, segment in enumerate(selected):
        source_row = source_rows[segment.source_episode_index]
        raw_slice = episode_slice(source_table, source_row).slice(segment.source_frame_start, segment.length)
        output_table = _replace_columns(raw_slice, episode_index=episode_index, global_start=global_index, fps=snapshot.fps)
        output_path = root / "data" / "chunk-000" / f"file-{episode_index:03d}.parquet"
        output_path.parent.mkdir(parents=True, exist_ok=True)
        pq.write_table(output_table, output_path, compression="snappy")
        for key, width in NUMERIC_WIDTHS.items():
            numeric_stats[key].update(np.asarray(output_table[key].to_pylist()))
        for key in INDEX_KEYS:
            scalar_stats[key].update(np.asarray(output_table[key].to_pylist(), dtype=np.float64).reshape(-1, 1))
        metadata_rows.append({
            "episode_index": episode_index,
            "tasks": ["flip table"],
            "length": segment.length,
            "dataset_from_index": global_index,
            "dataset_to_index": global_index + segment.length,
            "data/chunk_index": 0,
            "data/file_index": episode_index,
            "source_repo_id": config.source_repo_id,
            "source_revision": config.source_revision,
            "source_episode_index": segment.source_episode_index,
            "source_episode_name": source_episode_name(segment.source_episode_index),
            "source_frame_start": segment.source_frame_start,
            "source_frame_end": segment.source_frame_end + 1,
            "curation_verdict": segment.verdict,
            "curation_reviewer": segment.reviewer,
            "curation_reviewed_at": segment.reviewed_at,
            "curation_label": json.dumps(segment.label_row, ensure_ascii=False, sort_keys=True),
            "curation_split": segment.split,
            "curation_config_sha256": config.digest,
            "curation_code_sha256": config.code_digest,
            "curation_labels_revision": config.labels_revision,
            "curation_labels_sha256": selection_report["labels_sha256"],
        })
        global_index += segment.length
    video_mapping = _repack_videos(snapshot=snapshot, selected=selected, root=root, config=config)
    for metadata, segment in zip(metadata_rows, selected, strict=True):
        for key in VIDEO_KEYS:
            for field, value in video_mapping[(key, segment.source_episode_index)].items():
                metadata[f"videos/{key}/{field}"] = value
    meta_path = root / "meta" / "episodes" / "chunk-000" / "file-000.parquet"
    meta_path.parent.mkdir(parents=True, exist_ok=True)
    pq.write_table(pa.Table.from_pylist(metadata_rows), meta_path)
    pq.write_table(pa.Table.from_pylist([{"task_index": 0, "__index_level_0__": "flip table"}]), root / "meta" / "tasks.parquet")
    split_counts = {name: sum(segment.split == name for segment in selected) for name in ("train", "validation", "test")}
    split_start = 0
    splits: dict[str, str] = {}
    for name in ("train", "validation", "test"):
        split_end = split_start + split_counts[name]
        splits[name] = f"{split_start}:{split_end}"
        split_start = split_end
    info = json.loads(json.dumps(snapshot.info))
    info.update({"total_episodes": len(selected), "total_frames": global_index, "total_tasks": 1, "chunks_size": 1000, "data_files_size_in_mb": 100, "video_files_size_in_mb": int(config.section("video")["max_file_size_mb"]), "splits": splits})
    atomic_write_json(root / "meta" / "info.json", info)
    stats = {key: value.json() for key, value in numeric_stats.items()}
    stats.update({key: value.json() for key, value in scalar_stats.items()})
    atomic_write_json(root / "meta" / "stats.json", stats)
    curation_dir = root / "meta" / "curation"
    atomic_write_json(curation_dir / "selection.json", selection_report)
    manifest = {
        "schema_version": MANIFEST_SCHEMA,
        "config_sha256": config.digest,
        "code_sha256": config.code_digest,
        "source_repo_id": config.source_repo_id,
        "source_revision": config.source_revision,
        "labels_repo_id": config.labels_repo_id,
        "labels_revision": config.labels_revision,
        "labels_sha256": selection_report["labels_sha256"],
        "target_repo_id": config.target_repo_id,
        "video_pipeline_version": VIDEO_PIPELINE_VERSION,
        "episodes": metadata_rows,
        "split_counts": split_counts,
        "file_sha256": {},
    }
    manifest_path = root / MANIFEST_NAME
    atomic_write_json(manifest_path, manifest)
    (root / "README.md").write_text(_write_dataset_card(config, selection=selection_report, episodes=len(selected), frames=global_index), encoding="utf-8")
    manifest["file_sha256"] = file_manifest(root, exclude={MANIFEST_NAME, OWNED_MARKER})
    atomic_write_json(manifest_path, manifest)
    print(f"[build] root={root} episodes={len(selected)} frames={global_index}")
    return root
