def policy_names(
    config: dict[str, Any], policy_type: str, action_representation: str | None = None
) -> tuple[list[str], list[str]]:
    view_layout = view_layout_for_policy(config, policy_type)
    if view_layout == "real_g1_relative_eef_relative_joints":
        return (
            list(_mapping.REAL_G1_RELATIVE_EEF_STATE_NAMES),
            list(_mapping.REAL_G1_RELATIVE_EEF_ACTION_NAMES),
        )
    if view_layout == "robot_q_state19_action16":
        action_representation = resolve_action_representation(
            config, policy_type, action_representation
        )
        action_names = list(_mapping.UPPER_BODY_ACTION_NAMES)
        if action_representation == delta_action.ACTION_REPRESENTATION:
            action_names = [
                f"{name.removesuffix('_target')}_delta" for name in action_names[: delta_action.ARM_DIM]
            ] + action_names[delta_action.ARM_DIM :]
        return list(_mapping.UPPER_BODY_STATE_NAMES), action_names
    return full_robot_q_state_names(), full_robot_q_action_names()


