def fixed_size_float_array(pa: Any, rows: list[list[float]], size: int) -> Any:
    flat: list[float] = []
    for row in rows:
        if len(row) != size:
            raise ValueError(f"expected {size}-D vector, got {len(row)}")
        values = [float(value) for value in row]
        if not all(math.isfinite(value) for value in values):
            raise ValueError("policy vector contains NaN or Inf")
        flat.extend(values)
    return pa.FixedSizeListArray.from_arrays(pa.array(flat, type=pa.float32()), size)


def fixed_size_bool_array(pa: Any, rows: list[list[bool]], size: int) -> Any:
    flat: list[bool] = []
    for row in rows:
        if len(row) != size:
            raise ValueError(f"expected {size}-D boolean vector, got {len(row)}")
        flat.extend(bool(value) for value in row)
    return pa.FixedSizeListArray.from_arrays(pa.array(flat, type=pa.bool_()), size)


def load_progress_sidecar(path: Path) -> dict[int, dict[str, Any]]:
    if not path.is_file():
        raise FileNotFoundError(path)
    annotations: dict[int, dict[str, Any]] = {}
    for line_number, raw_line in enumerate(path.read_text().splitlines(), start=1):
        if not raw_line.strip():
            continue
        item = json.loads(raw_line)
        if item.get("schema_version") != "flip_table_event_progress_v1":
            raise ValueError(f"unsupported progress schema at {path}:{line_number}")
        episode_index = int(item["episode_index"])
        if episode_index in annotations:
            raise ValueError(f"duplicate progress annotation for episode {episode_index}")
        length = int(item["length"])
        if len(item["progress"]) != length or len(item["progress_mask"]) != length:
            raise ValueError(f"progress length mismatch for episode {episode_index}")
        annotations[episode_index] = item
    if not annotations:
        raise ValueError(f"progress sidecar is empty: {path}")
    return annotations


def progress_rows_for_table(
    table: Any,
    *,
    progress_annotations: dict[int, dict[str, Any]],
) -> tuple[list[list[float]], list[list[bool]]]:
    if "episode_index" not in table.schema.names or "frame_index" not in table.schema.names:
        raise KeyError("progress materialization requires episode_index and frame_index")
    cache: dict[int, tuple[list[list[float]], list[list[bool]]]] = {}
    values: list[list[float]] = []
    masks: list[list[bool]] = []
    for episode_value, frame_value in zip(
        table["episode_index"].to_pylist(),
        table["frame_index"].to_pylist(),
        strict=True,
    ):
        episode_index = int(episode_value)
        frame_index = int(frame_value)
        annotation = progress_annotations.get(episode_index)
        if annotation is None:
            raise KeyError(f"missing progress annotation for episode {episode_index}")
        if episode_index not in cache:
            cache[episode_index] = progress_horizons(
                annotation["progress"],
                annotation["progress_mask"],
                horizon=PROGRESS_HORIZON,
            )
        episode_values, episode_masks = cache[episode_index]
        if not 0 <= frame_index < len(episode_values):
            raise IndexError(
                f"frame {frame_index} is outside progress annotation for episode {episode_index}"
            )
        values.append(episode_values[frame_index])
        masks.append(episode_masks[frame_index])
    return values, masks


def as_float_list(values: list[Any]) -> list[float]:
    if not isinstance(values, (list, tuple)):
        raise TypeError(f"numeric feature row must be a list, got {type(values).__name__}")
    result = [float(value) for value in values]
    if not all(math.isfinite(value) for value in result):
        raise ValueError("source numeric feature contains NaN or Inf")
    return result


def concat_lists(values: Any) -> list[Any]:
    result: list[Any] = []
    for value in values:
        result.extend(copy.deepcopy(value))
    return result


